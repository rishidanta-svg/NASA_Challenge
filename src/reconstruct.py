"""Build a conservative, feature-separated coastal state from validated sensor edges.

This is v1 of the reconstruction layer, not a full terrain/bathymetry model.
It uses only satellite-derived boundary positions for the estimates. LiDAR
boundaries are copied into separate reference columns for later validation and
are NEVER used to calculate the satellite estimates.

Run from repository root:
    python src/reconstruct.py

Inputs (generated by the existing validation pipeline):
    outputs/sensor_boundaries.csv
    outputs/metrics.csv

Outputs:
    outputs/reconstructed_state.csv

Design:
- Waterline proxy: Sentinel-2 NDWI only. Tide-aware NDWI is retained as an
  experimental alternative, not silently substituted for the raw estimate.
- Dune-toe proxy: Sentinel-1 VV and VH, fused only because validation says both
  plausibly locate the dune toe. Inverse-error-variance weights are used.
  VV and VH are from the same sensor/acquisition, so the uncertainty is NOT
  reduced as if they were independent measurements.
- Radar boundary is never averaged with the waterline.
- Missing observations remain missing. No invented interpolation.
"""
from pathlib import Path
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs"
SENSOR_FILE = OUT / "sensor_boundaries.csv"
METRICS_FILE = OUT / "metrics.csv"
LIDAR_FILE = OUT / "lidar_boundaries.csv"
OUTPUT_FILE = OUT / "reconstructed_state.csv"

WATER_PRODUCT = "S2_NDWI"
EXPERIMENTAL_WATER_PRODUCT = "EXP_tideaware_S2"
DUNE_PRODUCTS = ("S1_VV", "S1_VH")


def rmse_lookup(metrics):
    """Return date-specific cross-validated RMSEs, excluding pooled rows."""
    required = {"product", "lidar_boundary", "date", "RMSE_m"}
    missing = required - set(metrics.columns)
    if missing:
        raise ValueError(f"metrics.csv missing columns: {sorted(missing)}")
    m = metrics[metrics.date != "pooled"]
    return {(r.product, r.lidar_boundary, r.date): float(r.RMSE_m)
            for r in m.itertuples() if np.isfinite(r.RMSE_m) and r.RMSE_m > 0}


def weighted_position(values, sigmas):
    """Inverse-variance weighted position; returns estimate and weights."""
    values = np.asarray(values, dtype=float)
    sigmas = np.asarray(sigmas, dtype=float)
    ok = np.isfinite(values) & np.isfinite(sigmas) & (sigmas > 0)
    if not ok.any():
        return np.nan, []
    w = 1.0 / np.square(sigmas[ok])
    return float(np.sum(w * values[ok]) / np.sum(w)), w.tolist()


def main():
    for f in (SENSOR_FILE, METRICS_FILE, LIDAR_FILE):
        if not f.exists():
            raise FileNotFoundError(f"Required input not found: {f}")

    sensors = pd.read_csv(SENSOR_FILE)
    metrics = pd.read_csv(METRICS_FILE)
    lidar = pd.read_csv(LIDAR_FILE)
    rmse = rmse_lookup(metrics)

    keys = ["date", "y"]
    base = sensors[keys].drop_duplicates().sort_values(keys).reset_index(drop=True)
    wide = sensors.pivot_table(index=keys, columns="product",
                               values="boundary_x", aggfunc="first").reset_index()
    state = base.merge(wide, on=keys, how="left")

    # Waterline: raw NDWI is the primary estimate. Its uncertainty is the
    # date-specific spatial-CV RMSE against the LiDAR wet/dry edge.
    state["waterline_x_m"] = state.get(WATER_PRODUCT, np.nan)
    state["waterline_sigma_m"] = [
        rmse.get((WATER_PRODUCT, "B1_wetdry", d), np.nan)
        for d in state.date
    ]
    state["waterline_source"] = np.where(
        state.waterline_x_m.notna(), "Sentinel-2 NDWI", "missing"
    )

    # Keep the tide-aware result visible as an experiment. It is not the
    # default because its pooled gain is mixed across dates.
    state["waterline_tideaware_experimental_x_m"] = state.get(
        EXPERIMENTAL_WATER_PRODUCT, np.nan
    )
    state["waterline_tideaware_sigma_m"] = [
        rmse.get((EXPERIMENTAL_WATER_PRODUCT, "B1_wetdry", d), np.nan)
        for d in state.date
    ]

    # Dune toe: fuse only the two Sentinel-1 polarizations validated against
    # the LiDAR dune toe. The weighted estimate is useful, but VV/VH are
    # correlated measurements from the same acquisition.
    dune_x, dune_sigma, vv_weights, vh_weights = [], [], [], []
    for r in state.itertuples():
        vv = getattr(r, "S1_VV", np.nan)
        vh = getattr(r, "S1_VH", np.nan)
        sv = rmse.get(("S1_VV", "B2_dunetoe", r.date), np.nan)
        sh = rmse.get(("S1_VH", "B2_dunetoe", r.date), np.nan)
        estimate, weights = weighted_position([vv, vh], [sv, sh])
        dune_x.append(estimate)
        # Conservative uncertainty: do not claim independent-sensor gain.
        valid_sigmas = [s for s, x in ((sv, vv), (sh, vh))
                        if np.isfinite(x) and np.isfinite(s)]
        dune_sigma.append(max(valid_sigmas) if valid_sigmas else np.nan)
        if len(weights) == 2:
            vv_weights.append(weights[0] / sum(weights))
            vh_weights.append(weights[1] / sum(weights))
        elif len(weights) == 1 and np.isfinite(vv):
            vv_weights.append(1.0); vh_weights.append(0.0)
        elif len(weights) == 1:
            vv_weights.append(0.0); vh_weights.append(1.0)
        else:
            vv_weights.append(np.nan); vh_weights.append(np.nan)

    state["dunetoe_x_m"] = dune_x
    state["dunetoe_sigma_conservative_m"] = dune_sigma
    state["dunetoe_weight_vv"] = vv_weights
    state["dunetoe_weight_vh"] = vh_weights
    state["dunetoe_source"] = np.where(
        state.dunetoe_x_m.notna(), "Sentinel-1 VV/VH weighted; correlated", "missing"
    )

    # Retain raw radar transitions separately. They are not relabelled as
    # waterline or dune toe unless the feature-specific validation supports it.
    state["radar_transition_vv_x_m"] = state.get("S1_VV", np.nan)
    state["radar_transition_vh_x_m"] = state.get("S1_VH", np.nan)

    # LiDAR reference positions are appended only for comparison/validation.
    # They are not inputs to any estimate above.
    refs = lidar[keys + ["B1_wetdry", "B2_dunetoe", "B3_contour"]].copy()
    refs = refs.rename(columns={
        "B1_wetdry": "validation_lidar_wetdry_x_m",
        "B2_dunetoe": "validation_lidar_dunetoe_x_m",
        "B3_contour": "validation_lidar_1p5m_contour_x_m",
    })
    state = state.merge(refs, on=keys, how="left")

    # Explicit interpretation flags prevent missing/weak evidence being
    # mistaken for a complete reconstructed coast.
    state["state_scope"] = "observed boundary features; not full terrain or bathymetry"
    state["waterline_status"] = np.where(
        state.waterline_x_m.notna(), "plausible; date-specific CV uncertainty",
        "not estimated"
    )
    state["dunetoe_status"] = np.where(
        state.dunetoe_x_m.notna(), "plausible; limited dune-toe coverage",
        "not estimated"
    )

    state.to_csv(OUTPUT_FILE, index=False, float_format="%.3f")
    print(f"Wrote {OUTPUT_FILE}")
    print(f"Rows: {len(state)}")
    print("Waterline estimates:", int(state.waterline_x_m.notna().sum()))
    print("Dune-toe estimates:", int(state.dunetoe_x_m.notna().sum()))
    print("LiDAR references are validation-only; not used in estimates.")


if __name__ == "__main__":
    main()
